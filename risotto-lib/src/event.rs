//! Collector-side representation of BMP messages (RFC 7854).
//!
//! An [`Event`] maps one-to-one to a BMP message type, with two exceptions:
//! - a Route Monitoring message is flattened into one event per prefix;
//! - a Termination event is synthesized (`synthetic = true`) when the BMP
//!   session ends without the router sending a Termination message.

use chrono::{DateTime, Utc};
use std::net::{IpAddr, Ipv4Addr};

/// BMP message types, as numbered in RFC 7854 section 4.1.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[repr(u8)]
pub enum MessageType {
    RouteMonitoring = 0,
    StatsReport = 1,
    PeerDown = 2,
    PeerUp = 3,
    Initiation = 4,
    Termination = 5,
    RouteMirroring = 6,
}

impl MessageType {
    pub fn as_str(&self) -> &'static str {
        match self {
            MessageType::RouteMonitoring => "route_monitoring",
            MessageType::StatsReport => "stats_report",
            MessageType::PeerDown => "peer_down",
            MessageType::PeerUp => "peer_up",
            MessageType::Initiation => "initiation",
            MessageType::Termination => "termination",
            MessageType::RouteMirroring => "route_mirroring",
        }
    }
}

#[derive(Debug, Clone, PartialEq)]
pub struct Event {
    /// Time at which the collector decoded the message.
    pub time_received: DateTime<Utc>,
    /// Router address (IPv4 addresses are mapped to IPv6).
    pub router_addr: IpAddr,
    pub router_port: u16,
    /// Time at which the BMP (TCP) session was established.
    /// Together with the router address and port, it identifies the session.
    pub session_start: DateTime<Utc>,
    /// Position of the event in its session, starting at 0 and incremented for every
    /// event. A gap means events were lost between the collector and the consumer.
    pub sequence: u64,
    /// True when the event was generated by the collector, not sent by the router.
    pub synthetic: bool,
    pub body: EventBody,
}

#[derive(Debug, Clone, PartialEq)]
pub enum EventBody {
    RouteMonitoring(PeerHeader, RouteMonitoring),
    StatsReport(PeerHeader, StatsReport),
    PeerDown(PeerHeader, PeerDown),
    PeerUp(PeerHeader, PeerUp),
    Initiation(Initiation),
    Termination(Termination),
    /// Route Mirroring content is not decoded (yet), only its per-peer header.
    RouteMirroring(PeerHeader),
}

impl EventBody {
    pub fn message_type(&self) -> MessageType {
        match self {
            EventBody::RouteMonitoring(..) => MessageType::RouteMonitoring,
            EventBody::StatsReport(..) => MessageType::StatsReport,
            EventBody::PeerDown(..) => MessageType::PeerDown,
            EventBody::PeerUp(..) => MessageType::PeerUp,
            EventBody::Initiation(..) => MessageType::Initiation,
            EventBody::Termination(..) => MessageType::Termination,
            EventBody::RouteMirroring(..) => MessageType::RouteMirroring,
        }
    }

    pub fn peer_header(&self) -> Option<&PeerHeader> {
        match self {
            EventBody::RouteMonitoring(h, _)
            | EventBody::StatsReport(h, _)
            | EventBody::PeerDown(h, _)
            | EventBody::PeerUp(h, _)
            | EventBody::RouteMirroring(h) => Some(h),
            EventBody::Initiation(_) | EventBody::Termination(_) => None,
        }
    }
}

/// BMP per-peer header (RFC 7854 section 4.2).
#[derive(Debug, Clone, PartialEq)]
pub struct PeerHeader {
    pub peer_type: u8,
    pub peer_flags: u8,
    pub peer_distinguisher: u64,
    /// Peer address (IPv4 addresses are mapped to IPv6).
    pub peer_addr: IpAddr,
    pub peer_asn: u32,
    pub peer_bgp_id: Ipv4Addr,
    pub timestamp: DateTime<Utc>,
    /// Derived from the L flag (RFC 7854).
    pub is_post_policy: bool,
    /// Derived from the O flag (RFC 8671).
    pub is_adj_rib_out: bool,
}

/// One prefix of a Route Monitoring message, with the attributes of its BGP UPDATE.
#[derive(Debug, Clone, PartialEq)]
pub struct RouteMonitoring {
    /// Prefix address (IPv4 addresses are mapped to IPv6).
    pub prefix_addr: IpAddr,
    pub prefix_len: u8,
    /// ADD-PATH path identifier (RFC 7911).
    pub path_id: Option<u32>,
    pub announced: bool,
    /// Address family of the prefix (1/1 for IPv4 unicast NLRI).
    pub afi: u16,
    pub safi: u8,
    /// Part of the initial table dump sent after Peer Up, i.e. received before the
    /// End-of-RIB marker of its peer, RIB view (pre/post-policy, Adj-RIB-In/Out) and family.
    /// Set by [`crate::BmpSession`].
    pub initial_dump: bool,

    pub origin: String,
    pub as_path: Vec<u32>,
    pub next_hop: Option<IpAddr>,
    pub multi_exit_discriminator: Option<u32>,
    pub local_preference: Option<u32>,
    pub only_to_customer: Option<u32>,
    pub atomic_aggregate: bool,
    pub aggregator_asn: Option<u32>,
    pub aggregator_bgp_id: Option<u32>,
    pub communities: Vec<(u32, u16)>,
    pub extended_communities: Vec<(u8, u8, Vec<u8>)>, // (type_high, type_low, value)
    pub large_communities: Vec<(u32, u32, u32)>,      // (global_admin, local_data1, local_data2)
    pub originator_id: Option<u32>,
    pub cluster_list: Vec<u32>,
    pub mp_reach_afi: Option<u16>,
    pub mp_reach_safi: Option<u8>,
    pub mp_unreach_afi: Option<u16>,
    pub mp_unreach_safi: Option<u8>,
}

/// Statistics Report (RFC 7854 section 4.8).
#[derive(Debug, Clone, PartialEq, Default)]
pub struct StatsReport {
    pub counters: Vec<StatCounter>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct StatCounter {
    pub stat_type: u16,
    /// Set for per-AFI/SAFI gauges.
    pub afi: Option<u16>,
    pub safi: Option<u8>,
    pub value: u64,
}

/// Peer Down Notification (RFC 7854 section 4.9).
#[derive(Debug, Clone, PartialEq, Default)]
pub struct PeerDown {
    pub reason: u8,
    /// Raw data following the reason code (BGP NOTIFICATION PDU, FSM event code or TLVs).
    pub data: Vec<u8>,
    /// BGP NOTIFICATION error code and subcode, for reasons 1 and 3.
    pub notification: Option<(u8, u8)>,
    /// FSM event code, for reason 2.
    pub fsm_event_code: Option<u16>,
}

/// Peer Up Notification (RFC 7854 section 4.10).
#[derive(Debug, Clone, PartialEq)]
pub struct PeerUp {
    /// Local address (IPv4 addresses are mapped to IPv6).
    pub local_addr: IpAddr,
    pub local_port: u16,
    pub remote_port: u16,
    pub sent_open: Option<OpenMessage>,
    pub received_open: Option<OpenMessage>,
    pub information: Vec<InformationTlv>,
}

/// The parts of a BGP OPEN message relevant to a session.
#[derive(Debug, Clone, PartialEq)]
pub struct OpenMessage {
    pub version: u8,
    /// 4-octet ASN when the capability is present, else the 2-octet "My AS" field.
    pub asn: u32,
    pub hold_time: u16,
    pub bgp_id: Ipv4Addr,
    /// Capability codes advertised in the OPEN message.
    pub capabilities: Vec<u8>,
}

/// Initiation Message (RFC 7854 section 4.3).
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Initiation {
    pub information: Vec<InformationTlv>,
}

/// Termination Message (RFC 7854 section 4.5).
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Termination {
    pub reason: Option<u16>,
    pub information: Vec<InformationTlv>,
}

/// Termination reason sent in synthetic Termination events (RFC 7854: "Unspecified reason").
pub const TERMINATION_REASON_UNSPECIFIED: u16 = 1;

/// Information TLV (string, sysDescr, sysName, ...).
#[derive(Debug, Clone, PartialEq)]
pub struct InformationTlv {
    pub info_type: u16,
    pub value: String,
}
